"""
generar_boss.py - Genera las 11 hojas de sprites de Sethur + SethurFrameData.cs (anclajes por fotograma).

Uso:   python3 generar_boss.py <carpeta_del_mod>
Salida: <mod>/Content/NPCs/Sethur/Anim/Sethur<Nombre>.png  (rejilla de COLS columnas, celdas de 224x256 con 2 px de separacion)
        <mod>/Content/NPCs/Sethur/SethurFrameData.cs
"""
import os
import sys
import time

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from boss import CELL_W, CELL_H, render_frame
from anims import ANIMS

COLS = 8
GUTTER = 2


def sheet_dims(n):
    rows = (n + COLS - 1) // COLS
    return COLS * (CELL_W + GUTTER) - GUTTER, rows * (CELL_H + GUTTER) - GUTTER


def main(mod_dir):
    out_dir = os.path.join(mod_dir, "Content", "NPCs", "Sethur", "Anim")
    os.makedirs(out_dir, exist_ok=True)
    anchors_all = {}
    problems = []
    t0 = time.time()
    for name, (fn, n, loop) in ANIMS.items():
        W, H = sheet_dims(n)
        sheet = np.zeros((H, W, 4), dtype=np.uint8)
        anc_list = []
        for i in range(n):
            kw = fn(i, n)
            p = kw.pop("p")
            px, anc = render_frame(p, **kw)
            col, row = i % COLS, i // COLS
            x0, y0 = col * (CELL_W + GUTTER), row * (CELL_H + GUTTER)
            sheet[y0:y0 + CELL_H, x0:x0 + CELL_W] = px
            # comprobacion de recorte: pixeles opacos en el borde de la celda
            a = px[..., 3] > 0
            cnt = int(a[:1, :].sum() + a[-1:, :].sum() + a[:, :1].sum() + a[:, -1:].sum())
            if cnt >= 12:
                problems.append("%s frame %d: %d px opacos en el borde de la celda (recorte)" % (name, i, cnt))
            anc_list.append(anc)
        Image.fromarray(sheet, "RGBA").save(os.path.join(out_dir, "Sethur%s.png" % name), optimize=True)
        anchors_all[name] = anc_list
        print("  %-11s %2d frames  -> %dx%d  (%.0fs)" % (name, n, W, H, time.time() - t0))

    # ---- SethurFrameData.cs
    lines = []
    lines.append("// <auto-generated> Generado por Herramientas/sprites/generar_boss.py. No editar a mano. </auto-generated>")
    lines.append("namespace ForgottenPharaoh.Content.NPCs.Sethur")
    lines.append("{")
    lines.append("\t/// <summary>Tamano de celda, rejilla y anclajes (en pixeles de celda) de cada fotograma de cada animacion.</summary>")
    lines.append("\tpublic static class SethurFrameData")
    lines.append("\t{")
    lines.append("\t\tpublic const int CellWidth = %d;" % CELL_W)
    lines.append("\t\tpublic const int CellHeight = %d;" % CELL_H)
    lines.append("\t\tpublic const int Columns = %d;" % COLS)
    lines.append("\t\tpublic const int Gutter = %d;" % GUTTER)
    lines.append("")
    lines.append("\t\t// Cada fotograma ocupa 8 valores: cabeza(x,y), orbe del baston(x,y), pecho(x,y), mano cercana(x,y)")
    for name, (fn, n, loop) in ANIMS.items():
        vals = []
        for anc in anchors_all[name]:
            for key in ("head", "orb", "chest", "near_hand"):
                x, y = anc.get(key, anc["chest"])
                vals.append("%d,%d" % (int(round(x)), int(round(y))))
        lines.append("\t\tpublic static readonly short[] %sAnchors = { %s };" % (name, ", ".join(vals)))
    lines.append("\t}")
    lines.append("}")
    with open(os.path.join(mod_dir, "Content", "NPCs", "Sethur", "SethurFrameData.cs"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # ---- portada (SethurBoss.png: textura por defecto del NPC / bestiario) = Idle frame 0 sin efectos
    fn, n, loop = ANIMS["Idle"]
    kw = fn(0, n)
    p = kw.pop("p")
    px, _ = render_frame(p, **kw)
    Image.fromarray(px, "RGBA").save(os.path.join(mod_dir, "Content", "NPCs", "Sethur", "SethurBoss.png"), optimize=True)

    if problems:
        print("AVISOS de recorte:")
        for pr in problems:
            print("  -", pr)
    else:
        print("Sin recortes en los bordes de celda.")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "ForgottenPharaoh"))
